export const formatPrice = (price, lang = 'ru') => {
  if (price === undefined || price === null) return '0';
  const formatted = price.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
  return `${formatted} ${translations[lang].currency}`;
};
